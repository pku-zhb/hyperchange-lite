    fun canonicalSource(text: String): String {
        val plain = if (text != compatibility) text.removeSuffix(compatibility) else text
        val title = presetPrefix.matchEntire(plain)?.groupValues?.get(2) ?: plain
        return units.replace(title, "")
    }

    fun resolve(text: String): Resolved? {
        resourceIds[canonicalSource(text)]?.let { return Resolved(it) }
        scopeNote.matchEntire(text)?.let {
            return Resolved(resourceIds.getValue("统一材质%s；锁屏范围%s（系统切换未模拟）"), it.groupValues.drop(1))
        }
        sidebarNote.matchEntire(text)?.let {
            return Resolved(resourceIds.getValue("统一侧栏%s；系统侧栏配方未还原"), it.groupValues.drop(1))
        }
        return null
    }

    fun resourceFor(text: String): Int? = resolve(text)?.id

    fun presetParts(text: String): Pair<String, String>? = presetPrefix.matchEntire(text)?.let {
        it.groupValues[1] to it.groupValues[2]
    }
}

@Composable
internal fun uiText(text: String): String {
    LocalConfiguration.current
    return localizedText(LocalContext.current, text)
}

internal fun localizedText(context: Context, text: String): String {
    val compatibility = "（注意兼容）"
    if (text != compatibility && text.endsWith(compatibility))
        return localizedText(context, text.removeSuffix(compatibility)) + localizedText(context, compatibility)
    UiTextCatalog.presetParts(text)?.let { (prefix, title) -> return prefix + localizedText(context, title) }
    val resolved = UiTextCatalog.resolve(text) ?: return text
    val template = context.getString(resolved.id)
    return if (resolved.arguments.isEmpty()) template else String.format(
        context.resources.configuration.locales[0] ?: Locale.getDefault(), template,
        *resolved.arguments.map { localizedText(context, it) }.toTypedArray(),
    )
}
